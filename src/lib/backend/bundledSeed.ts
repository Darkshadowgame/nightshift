import type { LatLng, SpotKind } from '../types';

/**
 * The SQL that puts Slipstream's own drives and photo spots on the server
 * (spots.bundled_id, migration 20261117190000_bundled_places.sql). Generated
 * from src/data/places.ts by scripts/seed-bundled-places.mjs, so the app and
 * the database never drift. Pure, so it's unit-tested.
 *
 * Drives and photo spots only: they're the places people finish, visit and
 * rate. Tracks and meet spots have nothing to count on the server (lap times
 * stay on the phone), so they stay in the app alone. Every photo spot is
 * seeded, unvetted ones too: the app decides what's on the map by id
 * (photoVetting.ts), and a row costs nothing.
 *
 * Idempotent: an upsert on bundled_id. A place renamed or moved in the app is
 * updated; one taken out of the app is left alone (completions keep their
 * history) and the app shows it as an ordinary place only if it still has one.
 */

export interface SeedPlace {
  id: string;
  kind: SpotKind;
  name: string;
  region: string;
  description: string;
  warnings?: string[];
  at: LatLng;
  path?: LatLng[];
  miles?: number;
}

/** Where the bundled places are seeded from: the kinds that take completions and ratings. */
export const SEEDED_KINDS: readonly SpotKind[] = ['drive', 'photo'];

const ID = /^[a-z0-9][a-z0-9-]{2,79}$/;

/** A SQL string literal ('' doubled). */
export function lit(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

function num(n: number): string {
  if (!Number.isFinite(n)) throw new Error(`Not a number: ${n}`);
  return String(Math.round(n * 1e6) / 1e6);
}

function point(p: LatLng): string {
  return `private.pt(${num(p.lat)}, ${num(p.lng)})`;
}

function line(path: LatLng[]): string {
  const coords = path.map((p) => `${num(p.lng)} ${num(p.lat)}`).join(', ');
  return `extensions.st_geogfromtext(${lit(`SRID=4326;LINESTRING(${coords})`)})`;
}

/** What's wrong with the list for the seed, or null. Checked before any SQL is made. */
export function seedProblem(places: readonly SeedPlace[]): string | null {
  const ids = new Set<string>();
  const names = new Set<string>();
  for (const p of places) {
    if (!ID.test(p.id)) return `Bad id: ${p.id}`;
    if (ids.has(p.id)) return `Duplicate id: ${p.id}`;
    ids.add(p.id);
    const name = p.name.trim().toLowerCase();
    if (names.has(name)) return `Duplicate name: ${p.name}`;
    names.add(name);
    if (p.name.trim().length < 3 || p.name.trim().length > 60) return `Name must be 3 to 60 characters: ${p.name}`;
    if (p.kind === 'drive' && (!p.path || p.path.length < 2)) return `Drive without a line: ${p.id}`;
  }
  return null;
}

/** The upsert for the drives and photo spots in `places`. Throws if the list has a problem. */
export function bundledSeedSql(places: readonly SeedPlace[], limits: Readonly<Record<string, number>> = {}): string {
  const seeded = places.filter((p) => SEEDED_KINDS.includes(p.kind));
  const problem = seedProblem(seeded);
  if (problem) throw new Error(problem);
  const rows = seeded.map((p) => {
    const warnings = p.warnings?.length ? `array[${p.warnings.map(lit).join(', ')}]::text[]` : `'{}'::text[]`;
    return `  (${[
      lit(p.id),
      lit(p.kind),
      lit(p.name.trim()),
      lit(p.description),
      point(p.at),
      p.kind === 'drive' && p.path ? line(p.path) : 'null',
      p.miles ? num(p.miles) : 'null',
      limits[p.id] ? num(limits[p.id]) : 'null',
      lit(p.region),
      warnings,
    ].join(', ')})`;
  });
  return [
    '-- GENERATED by scripts/seed-bundled-places.mjs from src/data/places.ts. Do not edit by hand.',
    `-- ${seeded.filter((p) => p.kind === 'drive').length} drives and ${seeded.filter((p) => p.kind === 'photo').length} photo spots, keyed by the app's stable ids (spots.bundled_id).`,
    '-- Safe to run again: an upsert on bundled_id. No author (nobody earns author rep), approved.',
    'insert into public.spots (bundled_id, kind, name, description, location, path, miles, limit_mph, region, warnings, author_id, status, approved_at)',
    'select v.bundled_id, v.kind::public.spot_kind, v.name, v.description, v.location, v.path, v.miles, v.limit_mph, v.region, v.warnings, null, \'approved\', now()',
    'from (values',
    rows.join(',\n'),
    ') as v (bundled_id, kind, name, description, location, path, miles, limit_mph, region, warnings)',
    'on conflict (bundled_id) do update set',
    '  kind = excluded.kind, name = excluded.name, description = excluded.description, location = excluded.location,',
    '  path = excluded.path, miles = excluded.miles, limit_mph = excluded.limit_mph, region = excluded.region,',
    "  warnings = excluded.warnings, author_id = null, status = 'approved', approved_at = coalesce(public.spots.approved_at, excluded.approved_at);",
    '',
  ].join('\n');
}
