/**
 * Real photos for the demo's sample builds, posts and photo spots, from
 * Wikimedia Commons. Free licences only (CC0, public domain, CC BY, CC BY-SA),
 * each credited on screen with its author and licence and linked to its Commons
 * page. Number plates are unreadable or blurred by us (marked `edited`).
 * Thumbnails are bundled at 480 px (4:3), so no network is needed to show them.
 */
export interface SamplePhoto {
  /** Bundled thumbnail (require of the jpg). */
  image: number;
  /** The Commons file page (credit, licence, the full picture). */
  page: string;
  /** What the photo shows, plain text, e.g. "BMW M4 Competition (G82)". */
  title: string;
  /** Plain-text author as Commons gives it (HTML stripped). */
  author: string;
  /** e.g. "CC BY-SA 4.0", "CC0", "Public domain". */
  licence: string;
  licenceUrl?: string;
  /** Set when the photo shows a close match, not the exact model: what it shows. */
  similar?: string;
  /** Set when we changed the picture, e.g. "Plate blurred". */
  edited?: string;
}

