-- Nightshift's own drives and photo spots on the server (REVIEW-5 M4).
--
-- The app ships its places in src/data/places.ts with stable string ids
-- ('dr-snake-pass'). Until now, finishing, visiting or rating one of them was
-- kept on the phone, so rep, "Driven by" and star averages differed from
-- phone to phone. These rows let the same RPCs (complete_drive, visit_spot,
-- rate_spot, spot_stats) work on them, so everyone sees the same numbers.
--
-- * spots.bundled_id: the app's stable id. Unique; null for places people
--   suggest. A bundled row has no author (nobody earns author rep for it) and
--   is written only by the seed (supabase/seed_bundled_places.sql, generated by
--   scripts/seed-bundled-places.mjs from src/data/places.ts). The app matches
--   rows to its bundled places by this id, never by name.
-- * spots.limit_mph: the road's limit where the app knows it (Spot.limitMph),
--   so complete_drive() judges the average speed like judgeRun() does.
-- * place_rep_for(): drives finished (with their length-tier rep) and photo
--   spots visited per person, as counts only (like road_rep_for()), so rep is
--   the same on every phone without saying who drove what, or when.

alter table public.spots
  add column bundled_id text,
  add column limit_mph numeric check (limit_mph is null or limit_mph between 10 and 70);

alter table public.spots
  add constraint spots_bundled_id_key unique (bundled_id),
  add constraint spots_bundled_id_format check (bundled_id is null or bundled_id ~ '^[a-z0-9][a-z0-9-]{2,79}$'),
  add constraint spots_bundled_no_author check (bundled_id is null or author_id is null);

-- The 8 circuits the first seed added match bundled tracks: give them their ids,
-- so the app shows each circuit once.
update public.spots s
set bundled_id = m.bundled_id
from (values
  ('silverstone', 'tr-silverstone'),
  ('brands hatch', 'tr-brands-hatch'),
  ('donington park', 'tr-donington'),
  ('oulton park', 'tr-oulton'),
  ('snetterton', 'tr-snetterton'),
  ('cadwell park', 'tr-cadwell'),
  ('anglesey circuit', 'tr-anglesey'),
  ('knockhill', 'tr-knockhill')
) as m (name, bundled_id)
where lower(s.name) = m.name and s.kind = 'track' and s.author_id is null and s.bundled_id is null;

-- The read view, with the two new columns at the end (create or replace keeps the grants).
create or replace view public.spots_list with (security_invoker = true) as
  select
    s.id, s.kind, s.name, s.description,
    extensions.st_y(s.location::extensions.geometry) as lat,
    extensions.st_x(s.location::extensions.geometry) as lng,
    case when s.path is null then null else (
      select jsonb_agg(
               jsonb_build_object('lat', extensions.st_y(d.geom), 'lng', extensions.st_x(d.geom))
               order by d.path)
      from extensions.st_dumppoints(s.path::extensions.geometry) d
    ) end as path,
    s.miles, s.author_id, s.status, s.created_at, s.ban_zone, s.warnings, s.region,
    s.bundled_id, s.limit_mph
  from public.spots s;

-- judgeRun() with the road's own limit where known (else MAX_AVERAGE_MPH, 45).
-- Otherwise unchanged from 20261117120300_rpc.sql.
create or replace function public.complete_drive(p_spot_id uuid, p_fixes jsonb)
returns jsonb
language plpgsql security definer
set search_path = ''
as $$
declare
  v_uid uuid := private.require_uid();
  s public.spots;
  v_n int;
  v_fix jsonb;
  v_t bigint;
  v_prev bigint;
  v_first bigint;
  v_miles double precision;
  v_hours double precision;
  i int;
  c_order constant text := 'Pass every checkpoint in order to finish.';
begin
  select * into s from public.spots where id = p_spot_id;
  if not found or s.kind <> 'drive' or s.path is null then
    return jsonb_build_object('ok', false, 'reason', 'Drive not found.');
  end if;
  if s.status <> 'approved' then
    return jsonb_build_object('ok', false, 'reason', 'This place is waiting for approval.');
  end if;
  v_n := extensions.st_npoints(s.path::extensions.geometry);
  if v_n < 2 then return jsonb_build_object('ok', false, 'reason', 'This drive has no checkpoints.'); end if;
  if p_fixes is null or jsonb_typeof(p_fixes) <> 'array' or jsonb_array_length(p_fixes) < v_n then
    return jsonb_build_object('ok', false, 'reason', c_order);
  end if;

  for i in 1 .. v_n loop
    v_fix := p_fixes -> (i - 1);
    v_t := (v_fix->>'t')::bigint;
    if v_t is null or (v_fix->>'lat') is null or (v_fix->>'lng') is null
       or (v_prev is not null and v_t < v_prev)
       or not extensions.st_dwithin(
         private.pt((v_fix->>'lat')::float8, (v_fix->>'lng')::float8),
         extensions.st_pointn(s.path::extensions.geometry, i)::extensions.geography,
         private.mi(0.2)) then
      return jsonb_build_object('ok', false, 'reason', c_order);
    end if;
    if i = 1 then v_first := v_t; end if;
    v_prev := v_t;
  end loop;

  if to_timestamp(v_prev / 1000.0) > now() + interval '5 minutes'
     or to_timestamp(v_prev / 1000.0) < now() - interval '1 hour' then
    return jsonb_build_object('ok', false, 'reason', 'That run is too old to count. Start again when you''re ready.');
  end if;

  v_miles := greatest(coalesce(s.miles, 0)::double precision, extensions.st_length(s.path) / 1609.344);
  if (v_prev - v_first) > (30 + v_miles * 6) * 60000 then
    return jsonb_build_object('ok', false, 'reason',
      'That took longer than a drive allows, so it doesn''t count. Start again when you''re ready.');
  end if;
  v_hours := (v_prev - v_first) / 3600000.0;
  if v_hours <= 0 or v_miles / v_hours > coalesce(s.limit_mph, 45)::double precision then
    return jsonb_build_object('ok', false, 'reason',
      'That was quicker than these roads allow at the speed limits, so it doesn''t count. Drives are never about speed.');
  end if;

  insert into public.spot_completions (spot_id, user_id, completed_on)
    values (s.id, v_uid, (now() at time zone 'Europe/London')::date)
    on conflict on constraint spot_completions_once_a_day do nothing;
  return jsonb_build_object('ok', true);
end;
$$;

-- driveTier(miles).rep from src/lib/rep.ts: short (< 10 mi) 50, medium 100,
-- long (25+) 175, epic (50+) 250; unknown length counts as medium.
create function private.drive_tier_rep(p_miles numeric)
returns int
language sql immutable
set search_path = ''
as $$
  select case
    when coalesce(nullif(p_miles, 0), 10) >= 50 then 250
    when coalesce(nullif(p_miles, 0), 10) >= 25 then 175
    when coalesce(nullif(p_miles, 0), 10) >= 10 then 100
    else 50
  end
$$;

-- repLedger()'s "Drives finished" and "Photo spots visited" lines for anyone:
-- approved places they didn't suggest, each counted once. Counts only, never
-- which place or which day.
create function public.place_rep_for(p_user_ids uuid[])
returns table (user_id uuid, drives int, drives_rep int, photo_spots int)
language sql stable security definer
set search_path = ''
as $$
  select u.id,
    (select count(*) from public.spots s
      where s.kind = 'drive' and s.status = 'approved' and s.author_id is distinct from u.id
        and exists (select 1 from public.spot_completions c where c.spot_id = s.id and c.user_id = u.id))::int,
    coalesce((select sum(private.drive_tier_rep(s.miles)) from public.spots s
      where s.kind = 'drive' and s.status = 'approved' and s.author_id is distinct from u.id
        and exists (select 1 from public.spot_completions c where c.spot_id = s.id and c.user_id = u.id)), 0)::int,
    (select count(*) from public.spots s
      where s.kind = 'photo' and s.status = 'approved' and s.author_id is distinct from u.id
        and exists (select 1 from public.spot_completions c where c.spot_id = s.id and c.user_id = u.id))::int
  from unnest(p_user_ids) as u (id)
  where auth.uid() is not null
$$;

revoke execute on function public.place_rep_for(uuid[]) from public, anon;
grant execute on function public.place_rep_for(uuid[]) to authenticated, service_role;
revoke execute on function private.drive_tier_rep(numeric) from public, anon;
grant execute on function private.drive_tier_rep(numeric) to authenticated, service_role;
